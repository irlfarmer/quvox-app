// Handle updating storage path
ipcMain.handle('update-storage-path', async (event, newPath: string) => {
  const oldPath = store.store.storagePath;
  
  // Create new directory if it doesn't exist
  if (!fs.existsSync(newPath)) {
    fs.mkdirSync(newPath, { recursive: true });
  }

  // Move existing screenshots if any exist
  if (fs.existsSync(oldPath)) {
    const files = fs.readdirSync(oldPath);
    for (const file of files) {
      const oldFilePath = path.join(oldPath, file);
      const newFilePath = path.join(newPath, file);
      fs.renameSync(oldFilePath, newFilePath);
    }
  }

  store.store = { ...store.store, storagePath: newPath };
  return true;
});

