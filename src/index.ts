// Handle getting recent screenshots
ipcMain.handle('get-recent-screenshots', async () => {
  try {
    const storagePath = store.store.storagePath;
    if (!fs.existsSync(storagePath)) {
      return [];
    }

    const files = await fs.promises.readdir(storagePath);
    const screenshots = await Promise.all(
      files
        .filter(file => file.endsWith('.png'))
        .map(async file => {
          const filePath = path.join(storagePath, file);
          const stats = await fs.promises.stat(filePath);
          
          // Try to read metadata if it exists
          let metadata: { id?: string; timestamp?: number; name?: string; activeWindow?: { title: string; app: string } } = {};
          const metaPath = filePath.replace('.png', '.json');
          if (fs.existsSync(metaPath)) {
            try {
              const metaContent = await fs.promises.readFile(metaPath, 'utf-8');
              metadata = JSON.parse(metaContent);
            } catch (error) {
              console.error('Error reading metadata for', file, error);
            }
          }

          // If no metadata file exists, create basic metadata
          if (!Object.keys(metadata).length) {
            metadata = {
              id: file.replace('.png', ''),
              timestamp: stats.mtime.getTime(),
              name: file
            };
            // Save this basic metadata for future use
            try {
              await fs.promises.writeFile(metaPath, JSON.stringify(metadata, null, 2));
            } catch (error) {
              console.error('Error saving basic metadata for', file, error);
            }
          }

          // Generate thumbnail from the image
          let thumbnail: string | undefined;
          let data: string | undefined;
          try {
            const imageBuffer = await fs.promises.readFile(filePath);
            const nativeImage = require('electron').nativeImage;
            const image = nativeImage.createFromBuffer(imageBuffer);
            
            // Set the full image data
            data = imageBuffer.toString('base64');
            
            // Create a thumbnail that's 400px wide (maintaining aspect ratio)
            const size = image.getSize();
            const scaleFactor = 400 / size.width;
            const thumbnailImage = image.resize({
              width: 400,
              height: Math.round(size.height * scaleFactor),
              quality: 'good'
            });
            thumbnail = thumbnailImage.toDataURL().split(',')[1]; // Remove the data:image/png;base64, prefix
          } catch (error) {
            console.error('Error generating thumbnail for', file, error);
          }

          return {
            id: metadata.id || file.replace('.png', ''),
            path: filePath,
            name: metadata.name || file,
            timestamp: metadata.timestamp || stats.mtime.getTime(),
            thumbnail,
            data,
            metadata
          };
        })
    );

    // Sort by timestamp, most recent first
    return screenshots.sort((a, b) => b.timestamp - a.timestamp);
  } catch (error) {
    console.error('Error getting recent screenshots:', error);
    return [];
  }
});

