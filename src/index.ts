// Handle screenshot capture request
ipcMain.handle('screenshot:capture', async (event, options) => {
  try {
    const { displayId } = options;
    const primaryDisplay = screen.getPrimaryDisplay();
    const { width, height } = primaryDisplay.bounds;

    const sources = await desktopCapturer.getSources({
      types: ['screen'],
      thumbnailSize: { width, height }
    });

    const source = displayId
      ? sources.find(s => s.display_id === displayId)
      : sources[0];

    if (!source || !source.thumbnail) {
      throw new Error('Failed to capture screenshot');
    }

    // Get active window information
    const activeWindow = await activeWin.activeWindow();

    // Create screenshot data
    const timestamp = Date.now();
    const id = `screenshot_${timestamp}`;
    const screenshotBuffer = source.thumbnail.toPNG();
    const base64Data = screenshotBuffer.toString('base64');

    // Create metadata
    const metadata = {
      id,
      timestamp,
      source: 'button',
      category: 'manual',
      activeWindow: activeWindow ? {
        title: activeWindow.title,
        app: activeWindow.owner.name,
        path: activeWindow.owner.path
      } : undefined
    };

    // Get storage path from settings
    const savePath = path.join(store.store.storagePath, `${id}.png`);
    const metaPath = savePath.replace('.png', '.json');

    // Save the screenshot and metadata
    const screenshotData = await handleScreenshotSave(event, {
      screenshot: base64Data,
      savePath,
      metaPath,
      metadata
    });

    return base64Data;
  } catch (error) {
    console.error('Error capturing screenshot:', error);
    return null;
  }
});

