// Handle getting available apps
ipcMain.handle('get-available-apps', async () => {
  try {
    let apps: { name: string; icon?: string; isActive: boolean }[] = [];

    if (process.platform === 'win32') {
      // Get running apps on Windows using PowerShell
      const { stdout } = await execAsync('powershell "Get-Process | Where-Object {$_.MainWindowTitle} | Select-Object ProcessName"');
      apps = stdout.split('\n')
        .filter(line => line.trim() && !line.includes('ProcessName'))
        .map(line => ({
          name: line.trim(),
          isActive: true,
        }));
    } else if (process.platform === 'darwin') {
      // Get running apps on macOS
      const { stdout } = await execAsync('ps -axo comm=');
      apps = stdout.split('\n')
        .filter(line => line.trim() && !line.includes('ps'))
        .map(line => ({
          name: path.basename(line.trim(), '.app'),
          isActive: true,
        }));
    }

    return apps;
  } catch (error) {
    console.error('Error getting available apps:', error);
    return [];
  }
});

