// Register global shortcut
const registerGlobalShortcut = () => {
  const settings = store.store;
  const { shortcut } = settings;
  
  // Unregister any existing shortcuts first
  globalShortcut.unregisterAll();
  
  // Build the accelerator string
  const accelerator = [
    shortcut.ctrl ? 'CommandOrControl' : '',
    shortcut.shift ? 'Shift' : '',
    shortcut.alt ? 'Alt' : '',
    shortcut.key
  ].filter(Boolean).join('+');
  
  try {
    globalShortcut.register(accelerator, async () => {
      const mainWindow = BrowserWindow.getAllWindows()[0];
      if (!mainWindow) return;
      
      try {
        // Get active window information first
        const activeWindow = await activeWin.activeWindow();
        
        // Then capture the screenshot
        const base64Data = await desktopCapturer.getSources({
          types: ['screen'],
          thumbnailSize: screen.getPrimaryDisplay().bounds
        }).then(sources => sources[0]?.thumbnail?.toPNG().toString('base64'));
        
        if (!base64Data) {
          console.error('Failed to capture screenshot in shortcut handler');
          return;
        }
        
        // Get settings here to avoid scoping issues
        const currentSettings = store.store;
        
        // Create screenshot metadata
        const timestamp = Date.now();
        const id = `screenshot_${timestamp}`;
        const filePath = path.join(currentSettings.storagePath, `${id}.png`);
        const metaPath = filePath.replace('.png', '.json');
        
        const metadata = {
          id,
          timestamp,
          name: path.basename(filePath),
          source: 'shortcut',
          category: 'manual',
          activeWindow: activeWindow ? {
            title: activeWindow.title,
            app: activeWindow.owner.name,
            path: activeWindow.owner.path
          } : undefined
        };

        // Save the screenshot and get the data
        const screenshotData = await handleScreenshotSave(null, {
          screenshot: base64Data,
          savePath: filePath,
          metaPath,
          metadata
        });

        return screenshotData;
      } catch (error) {
        console.error('Error taking screenshot via shortcut:', error);
      }
    });
  } catch (error) {
    console.error('Error registering global shortcut:', error);
  }
};

