// Handle notifications properly
const showNotification = (title: string, body: string, icon?: Electron.NativeImage, screenshotPath?: string) => {
  // Create notification config
  const notificationConfig = {
    title: `Quvox - ${title}`,
    body,
    icon,
    silent: false,
    screenshotPath
  };

  // If window is visible and focused, send event to renderer
  if (mainWindow?.isVisible() && mainWindow?.isFocused()) {
    mainWindow.webContents.send('show-notification', notificationConfig);
  } else {
    // Use native notification if window is minimized or unfocused
    const notification = new Notification(notificationConfig);
    notification.show();
    
    // Open the screenshot when notification is clicked
    notification.on('click', async () => {
      if (screenshotPath) {
        try {
          await shell.openPath(screenshotPath);
        } catch (error) {
          console.error('Error opening screenshot:', error);
          mainWindow?.show();
        }
      } else {
        mainWindow?.show();
      }
    });
  }
};

// Update screenshot save handler
async function handleScreenshotSave(event: any, { screenshot, savePath, metaPath, metadata }: { screenshot: string; savePath: string; metaPath: string; metadata: any }) {
  try {
    // Save the screenshot
    const screenshotBuffer = Buffer.from(screenshot, 'base64');
    await fs.promises.writeFile(savePath, screenshotBuffer);
    
    // Save the metadata
    if (metaPath) {
      await fs.promises.writeFile(metaPath, JSON.stringify(metadata, null, 2));
    }
    
    // Create screenshot data with consistent metadata
    const screenshotData = {
      id: metadata?.id || path.basename(savePath, '.png'),
      timestamp: metadata?.timestamp || Date.now(),
      path: savePath,
      name: path.basename(savePath),
      thumbnail: screenshot,
      metadata: {
        ...metadata,
        source: metadata?.source || 'manual',
        category: metadata?.category || 'uncategorized',
        activeWindow: metadata?.activeWindow || undefined
      }
    };

    // Send screenshot:captured event to renderer and show notification
    if (store.store.showNotifications) {
      // Create a native image from the screenshot buffer for the notification
      const notificationIcon = nativeImage.createFromBuffer(screenshotBuffer);
      
      // Resize the icon to a reasonable size for the notification (e.g., 256x256)
      const size = notificationIcon.getSize();
      const scaleFactor = 256 / Math.max(size.width, size.height);
      const resizedIcon = notificationIcon.resize({
        width: Math.round(size.width * scaleFactor),
        height: Math.round(size.height * scaleFactor),
        quality: 'good'
      });

      const notificationMessage = metadata?.activeWindow?.app 
        ? `Screenshot taken from ${metadata.activeWindow.app}`
        : 'Screenshot captured';

      showNotification(
        'Screenshot Captured',
        notificationMessage,
        resizedIcon,
        savePath
      );
    }

    // Always send the event to renderer for state updates
    mainWindow?.webContents.send('screenshot:captured', screenshotData);

    return screenshotData;
  } catch (error) {
    console.error('Error saving screenshot:', error);
    return false;
  }
}

