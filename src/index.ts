// Update create-flow handler to use synced session
ipcMain.handle('create-flow', async (event, { name, app_id, resolution, flow_type, is_published }) => {
  try {
    if (!currentSession) {
      console.error('No authenticated session found');
      return { error: 'Authentication required' };
    }

    const { data, error } = await supabase.rpc('create_flow', {
      p_name: name,
      p_app_id: app_id,
      p_resolution: resolution,
      p_flow_type: flow_type,
      p_is_published: is_published,
      p_user_id: currentSession.user.id
    });

    if (error) {
      console.error('Error from create_flow RPC:', error);
      return { error: error.message };
    }

    if (!data || !Array.isArray(data) || data.length === 0) {
      console.error('Invalid response from create_flow RPC:', data);
      return { error: 'Invalid response from server' };
    }

    // Extract the flow from the array and check for error
    const flow = data[0];
    if (flow.error) {
      console.error('Error in flow response:', flow.error);
      return { error: flow.error };
    }

    // Check for valid flow data
    if (!flow.id) {
      console.error('Flow response missing ID:', flow);
      return { error: 'Flow response missing ID' };
    }

    return { data: flow };
  } catch (error) {
    console.error('Error creating flow record:', error);
    return { error: error instanceof Error ? error.message : 'Unknown error occurred' };
  }
});

