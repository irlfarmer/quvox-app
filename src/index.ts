// Set up Content Security Policy
const setupCSP = () => {
  session.defaultSession.webRequest.onHeadersReceived((details, callback) => {
    const supabaseUrl = process.env.SUPABASE_URL;
    if (!supabaseUrl) {
      console.error('SUPABASE_URL environment variable is not set');
      app.quit();
      return;
    }

    // Extract the hostname from the Supabase URL
    const supabaseHostname = new URL(supabaseUrl).hostname;

    // Define CSP directives based on environment
    const scriptSrcDirectives = isDevelopment
      ? "'self' 'unsafe-eval' 'unsafe-inline'"
      : "'self'";

    const connectSrcDirectives = isDevelopment
      ? `'self' https://${supabaseHostname} wss://${supabaseHostname} ws://localhost:3000 http://localhost:3000`
      : `'self' https://${supabaseHostname} wss://${supabaseHostname}`;

    callback({
      responseHeaders: {
        ...details.responseHeaders,
        'Content-Security-Policy': [
          `default-src 'self' https://${supabaseHostname};`,
          `script-src ${scriptSrcDirectives};`,
          "style-src 'self' 'unsafe-inline';",
          "img-src 'self' data: blob: file:;",
          `connect-src ${connectSrcDirectives};`,
          "font-src 'self';"
        ].join(' ')
      }
    });
  });
};

